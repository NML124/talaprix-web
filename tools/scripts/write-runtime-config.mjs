import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const workspaceRoot = process.cwd();
const envPath = resolve(workspaceRoot, '.env');
const webOutput = resolve(
  workspaceRoot,
  'apps/web/src/environments/runtime-config.generated.ts',
);
const adminOutput = resolve(
  workspaceRoot,
  'apps/admin/src/environments/runtime-config.generated.ts',
);
const values = { ...process.env };
// Web Analytics site tokens are public identifiers, not API credentials.
const defaultWebAnalyticsToken = '6049036f3345421b889de629e9939dd0';

try {
  const source = await readFile(envPath, 'utf8');
  for (const line of source.split(/\r?\n/u)) {
    const match = line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*?)\s*$/u);
    if (!match) continue;
    const [, key, rawValue] = match;
    if (!values[key]) values[key] = rawValue.replace(/^(['"])(.*)\1$/u, '$2');
  }
} catch (error) {
  if (
    !(error instanceof Error) ||
    !('code' in error && error.code === 'ENOENT')
  )
    throw error;
}

const config = {
  supabaseUrl: values['SUPABASE_URL'] ?? '',
  supabaseAnonKey: values['SUPABASE_ANON_KEY'] ?? '',
};
// Public Mapbox token (pk.…), restricted to the site URLs in the Mapbox dashboard.
const mapboxToken =
  values['MAPBOX_PUBLIC_TOKEN'] || values['MAPBOX_API_KEY'] || '';
if (mapboxToken && !mapboxToken.startsWith('pk.'))
  console.warn(
    '[runtime-config] Mapbox token ignored: the website needs a public "pk." token, never a secret "sk." one.',
  );
const mapboxConfig = {
  token: mapboxToken.startsWith('pk.') ? mapboxToken : '',
  style: values['MAPBOX_STYLE'] || 'mapbox://styles/mapbox/streets-v12',
};
function configSource(value, mapbox) {
  const types = mapbox
    ? 'MapboxRuntimeConfig, SupabaseRuntimeConfig'
    : 'SupabaseRuntimeConfig';
  const source = `// Generated by tools/scripts/write-runtime-config.mjs. Do not edit.\nimport type { ${types} } from '@talaprix/shared/data-access';\n\nexport const runtimeConfig: SupabaseRuntimeConfig = ${JSON.stringify(value, null, 2)};\n`;
  return mapbox
    ? `${source}\nexport const mapboxConfig: MapboxRuntimeConfig = ${JSON.stringify(mapbox, null, 2)};\nexport const webAnalyticsToken = ${JSON.stringify(values['WEB_ANALYTICS_TOKEN'] || defaultWebAnalyticsToken)};\n`
    : source;
}

const adminConfig = {
  supabaseUrl: values['ADMIN_SUPABASE_URL'] ?? '',
  supabaseAnonKey: values['ADMIN_SUPABASE_ANON_KEY'] ?? '',
};

await Promise.all(
  [
    [webOutput, config, mapboxConfig],
    [adminOutput, adminConfig, null],
  ].map(async ([outputPath, value, mapbox]) => {
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, configSource(value, mapbox), 'utf8');
  }),
);
