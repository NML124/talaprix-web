import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const workspaceRoot = process.cwd();
const envPath = resolve(workspaceRoot, '.env');
const outputPath = resolve(
  workspaceRoot,
  'apps/web/src/environments/runtime-config.generated.ts',
);
const values = { ...process.env };

try {
  const source = await readFile(envPath, 'utf8');
  for (const line of source.split(/\r?\n/u)) {
    const match = line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*?)\s*$/u);
    if (!match) continue;
    const [, key, rawValue] = match;
    if (!values[key]) values[key] = rawValue.replace(/^(['"])(.*)\1$/u, '$2');
  }
} catch (error) {
  if (
    !(error instanceof Error) ||
    !('code' in error && error.code === 'ENOENT')
  )
    throw error;
}

const config = {
  supabaseUrl: values['SUPABASE_URL'] ?? '',
  supabaseAnonKey: values['SUPABASE_ANON_KEY'] ?? '',
};
const content = `// Generated by tools/scripts/write-runtime-config.mjs. Do not edit.\nimport type { SupabaseRuntimeConfig } from '@talaprix/shared/data-access';\n\nexport const runtimeConfig: SupabaseRuntimeConfig = ${JSON.stringify(config, null, 2)};\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, content, 'utf8');
